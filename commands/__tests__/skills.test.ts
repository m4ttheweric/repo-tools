function computeGolden(mattstackDir: string) {
  const roots: PluginRoots = {
    byName: {
      mattstack: { dir: join(mattstackDir, "plugins", "mattstack"), version: "1.2.0" },
      acme: { dir: join(mattstackDir, "plugins", "acme"), version: "0.3.0" },
    },
  };
  const verb: VerbDef = { name: "watch-ci", engine: "watch-ci", description: "Use when watching or triaging CI." };
  const step = loadStepSource("watch-ci", roots);
  const domain = loadAttachment("acme:watch-ci-domain", "domain", roots);
  const forge = loadAttachment("mattstack:gitlab-forge", "forge", roots);
  const invocable = invocableRoster(roots);
  return compileSkill(verb, step, { domain, forge }, invocable);
}

let logSpy: ReturnType<typeof spyOn>;
let logs: string[];

beforeEach(() => {
  logs = [];
  logSpy = spyOn(console, "log").mockImplementation((...args: unknown[]) => {
    logs.push(args.map(String).join(" "));
  });
});

afterEach(() => {
  logSpy.mockRestore();
  // skillsCheck sets this on staleness; Bun ignores process.exitCode = undefined once
  // truthy, so 0 is the only value that clears it before the suite's own exit status.
  process.exitCode = 0;
});

/**
 * Expected/domain errors print a clean one-liner and process.exit(1) instead
 * of throwing a bare stack trace (matches commands/secrets.ts,
 * commands/settings-keys.ts). Mock process.exit to throw a sentinel so the
 * real test process never dies, and read the spies' recorded calls BEFORE
 * mockRestore() -- bun's mockRestore() clears .mock.calls, unlike jest's.
 */
async function runExpectingCleanExit(fn: () => Promise<void>): Promise<{ exitCode: number | undefined; errors: string[] }> {
  const errors: string[] = [];
  const exitSpy = spyOn(process, "exit").mockImplementation(() => {
    throw new Error("process.exit sentinel");
  });
  const errorSpy = spyOn(console, "error").mockImplementation((...args: unknown[]) => {
    errors.push(args.map(String).join(" "));
  });
  try {
    await fn();
    return { exitCode: undefined, errors };
  } catch {
    const exitCode = exitSpy.mock.calls.at(-1)?.[0] as number | undefined;
    return { exitCode, errors };
  } finally {
    exitSpy.mockRestore();
    errorSpy.mockRestore();
  }
}

